// Copies the Web Awesome files the app uses into web/lib/webawesome/
// (docs/plan.md section 2, S-BACK-021). Source: the pinned
// @awesome.me/webawesome devDependency, its browser build (dist-cdn) - plain
// ES modules with Lit bundled, so the copied files run with no build step.
//
// Only the COMPONENTS below and the stock theme CSS are copied, plus every
// file they import (followed transitively), so unused parts of the library
// never ship. Re-run after changing COMPONENTS or bumping the package:
//   pnpm run vendor:webawesome
// Never hand-edit web/lib/webawesome/ - it is generated, like web/assets/.
// CodeQL skips it (.github/codeql/codeql-config.yml).

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const COMPONENTS = [
  'badge', 'button', 'button-group', 'callout', 'card', 'comparison', 'details',
  'dialog', 'drawer', 'dropdown', 'dropdown-item', 'input', 'option', 'popup',
  'progress-bar', 'select', 'slider', 'spinner', 'switch', 'tab', 'tab-group',
  'tab-panel', 'tooltip',
];
// Stock theme + the layer order our theme-broadcast.css overrides into.
export const STYLES = ['styles/themes/default.css'];
// Public entry: registerIconLibrary / setBasePath without importing hashed chunks.
export const ENTRY = 'webawesome.js';

const JS_IMPORT = /(?:^|[;\s])(?:import|export)\s*(?:[\w*{}\s,]+\s*from\s*)?["'](\.{1,2}\/[^"']+)["']/g;
const CSS_IMPORT = /@import\s+url\(\s*["']?(\.{1,2}\/[^"')]+)["']?\s*\)/g;

// Relative imports of one file, as paths relative to the package root.
export function importsOf(file, source) {
  const re = file.endsWith('.css') ? CSS_IMPORT : JS_IMPORT;
  const dir = path.posix.dirname(file);
  return [...source.matchAll(re)].map((m) => path.posix.normalize(path.posix.join(dir, m[1])));
}

// Every file reachable from `entries`; `read(p)` returns the source or undefined.
export function closure(entries, read) {
  const seen = new Set();
  const stack = [...entries];
  while (stack.length) {
    const file = stack.pop();
    if (seen.has(file)) continue;
    const src = read(file);
    if (src === undefined) throw new Error(`vendor-webawesome: ${file} not found in the package`);
    seen.add(file);
    stack.push(...importsOf(file, src));
  }
  return seen;
}

function main() {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
  const pkgDir = path.join(root, 'node_modules/@awesome.me/webawesome');
  const src = path.join(pkgDir, 'dist-cdn');
  const out = path.join(root, 'web/lib/webawesome');
  const version = JSON.parse(fs.readFileSync(path.join(pkgDir, 'package.json'), 'utf8')).version;

  const entries = [ENTRY, ...COMPONENTS.map((c) => `components/${c}/${c}.js`), ...STYLES];
  const read = (p) => { try { return fs.readFileSync(path.join(src, p), 'utf8'); } catch { return undefined; } };
  const files = [...closure(entries, read)].sort();

  fs.rmSync(out, { recursive: true, force: true });
  for (const f of files) {
    fs.mkdirSync(path.join(out, path.dirname(f)), { recursive: true });
    fs.copyFileSync(path.join(src, f), path.join(out, f));
  }
  const license = ['LICENSE.md', 'LICENSE'].map((l) => path.join(pkgDir, l)).find((l) => fs.existsSync(l));
  if (license) fs.copyFileSync(license, path.join(out, 'LICENSE.md'));
  fs.writeFileSync(path.join(out, 'README.md'),
    `# Web Awesome ${version} (vendored subset)\n\nGenerated by \`scripts/vendor-webawesome.mjs\` - do not edit.\n` +
    `Components: ${COMPONENTS.join(', ')}.\n${files.length} files.\n`);
  const bytes = files.reduce((n, f) => n + fs.statSync(path.join(out, f)).size, 0);
  console.log(`vendor-webawesome: ${version}, ${files.length} files, ${(bytes / 1024).toFixed(0)} KB -> web/lib/webawesome/`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
